import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { prepareWorktree, removeWorktree } from '../lib/worktrees.mjs';

const git = (repo, ...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8', windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] }).trim();
test('worktrees fetch the remote base, share ignored dependencies and remove only links', async t => {
  const root = mkdtempSync(join(tmpdir(), 'atelier-worktrees-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const remote = join(root, 'remote'), source = join(root, 'source');
  mkdirSync(remote);
  git(remote, 'init', '-b', 'master');
  git(remote, 'config', 'user.email', 'test@example.invalid'); git(remote, 'config', 'user.name', 'Test');
  writeFileSync(join(remote, '.gitignore'), 'node_modules/\npackages/\n');
  mkdirSync(join(remote, 'front')); writeFileSync(join(remote, 'front', 'index.js'), 'initial');
  git(remote, 'add', '.'); git(remote, 'commit', '-m', 'initial');
  git(root, 'clone', remote, source);
  const local = git(source, 'rev-parse', 'HEAD');
  writeFileSync(join(remote, 'front', 'index.js'), 'updated'); git(remote, 'commit', '-am', 'update');
  const latest = git(remote, 'rev-parse', 'HEAD');
  for (const entry of ['node_modules', 'front/node_modules', 'packages/Example.1.0']) mkdirSync(join(source, entry), { recursive: true });
  writeFileSync(join(source, 'node_modules', 'keep.txt'), 'keep');
  writeFileSync(join(source, 'packages/Example.1.0/example.nupkg'), 'package');
  writeFileSync(join(source, 'front/index.js'), 'local dirty source');
  const card = { id: 'a', repo: source, title: 'Test', branch: 'feature/test', baseBranch: 'master' };
  const attempts = await Promise.allSettled([prepareWorktree(card, {}), prepareWorktree(card, {})]);
  assert.equal(attempts.filter(result => result.status === 'fulfilled').length, 1);
  assert.equal(attempts.filter(result => result.status === 'rejected').length, 1);
  card.worktree = attempts.find(result => result.status === 'fulfilled').value;
  assert.equal(card.worktree.baseCommit, latest);
  assert.equal(git(card.worktree.path, 'rev-parse', 'HEAD'), latest);
  assert.equal(git(source, 'rev-parse', 'HEAD'), local);
  assert.equal(readFileSync(join(source, 'front/index.js'), 'utf8'), 'local dirty source');
  assert.equal(card.worktree.links.length, 3);
  for (const link of card.worktree.links) {
    assert.equal(lstatSync(join(card.worktree.path, link.path)).isSymbolicLink(), true);
    assert.equal(realpathSync(join(card.worktree.path, link.path)), link.target);
  }
  assert.equal(git(card.worktree.path, 'status', '--porcelain'), '');
  writeFileSync(join(card.worktree.path, 'front/index.js'), 'dirty');
  writeFileSync(join(card.worktree.path, 'untracked.txt'), 'local file');
  assert.equal(await prepareWorktree(card, {}), card.worktree);
  await assert.rejects(() => removeWorktree(card), /Git/);
  assert.equal(lstatSync(join(card.worktree.path, 'node_modules')).isSymbolicLink(), true);
  assert.equal(readFileSync(join(card.worktree.path, 'front/index.js'), 'utf8'), 'dirty');
  assert.equal(readFileSync(join(card.worktree.path, 'untracked.txt'), 'utf8'), 'local file');
  git(source, 'worktree', 'lock', card.worktree.path);
  await assert.rejects(() => removeWorktree(card, true), /locked/);
  assert.equal(lstatSync(join(card.worktree.path, 'node_modules')).isSymbolicLink(), true);
  git(source, 'worktree', 'unlock', card.worktree.path);
  await removeWorktree(card, true);
  assert.equal(existsSync(card.worktree.path), false);
  assert.equal(readFileSync(join(source, 'node_modules/keep.txt'), 'utf8'), 'keep');
  assert.equal(git(source, 'rev-parse', 'feature/test'), latest);
  delete card.worktree;
  writeFileSync(join(remote, 'front/index.js'), 'newer'); git(remote, 'commit', '-am', 'newer');
  card.worktree = await prepareWorktree(card, { baseBranch: 'HEAD' });
  assert.equal(git(card.worktree.path, 'rev-parse', 'HEAD'), latest, 'existing task branch is preserved');
  writeFileSync(join(card.worktree.path, 'front/index.js'), 'discard only this worktree');
  await removeWorktree(card, true);
  assert.equal(readFileSync(join(source, 'node_modules/keep.txt'), 'utf8'), 'keep');
  const fresh = { id: 'b', title: 'Fresh', repo: source };
  fresh.worktree = await prepareWorktree(fresh, {});
  assert.equal(git(fresh.worktree.path, 'rev-parse', 'HEAD'), git(remote, 'rev-parse', 'HEAD'));
  await removeWorktree(fresh);
  git(source, 'remote', 'set-url', 'origin', join(root, 'missing'));
  await assert.rejects(() => prepareWorktree({ id: 'c', title: 'Offline', repo: source }, {}), /Git/);
  assert.equal(git(source, 'worktree', 'list', '--porcelain').split('worktree ').length, 2);
});
